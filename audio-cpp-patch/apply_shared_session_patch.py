"""Share identical normal/stable model sessions instead of loading weights twice.

Only the two Irodori IDs generated by this installer are eligible. A stable alias
may share the normal session only when every model/session setting is identical
and neither has voice presets. Stable behavior remains request-scoped options.
"""
import argparse
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument("source", type=Path)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
path = args.source / "app/server/runtime.cpp"
text = path.read_text(encoding="utf8")
marker = "// ivr_shared_session_v1: stable is a request profile, not a second model."
anchor = """        load_voice_presets(*loaded);
        if (!loaded->config.lazy) {"""
insert = """        // ivr_shared_session_v1: stable is a request profile, not a second model.
        if (loaded->config.id == "irodori-500m-v3-q8-voice-stable-speaker") {
            const auto normal = model_index_.find("irodori-500m-v3-q8");
            if (normal != model_index_.end() && normal->second < models_.size()) {
                const auto & existing = models_.at(normal->second)->config;
                const auto & alias = loaded->config;
                const bool identical = existing.path == alias.path &&
                    existing.family == alias.family && existing.task == alias.task &&
                    existing.mode == alias.mode &&
                    existing.model_spec_override == alias.model_spec_override &&
                    existing.config_id == alias.config_id && existing.weight_id == alias.weight_id &&
                    existing.load_options == alias.load_options &&
                    existing.session_options == alias.session_options &&
                    existing.voice_presets.empty() && alias.voice_presets.empty() &&
                    !existing.default_voice_preset && !alias.default_voice_preset &&
                    !existing.default_voice_preset_id && !alias.default_voice_preset_id;
                if (identical) {
                    model_index_.at(alias.id) = normal->second;
                    loaded->config.lazy = true;
                    models_.push_back(std::move(loaded));
                    continue;
                }
            }
        }
        load_voice_presets(*loaded);
        if (!loaded->config.lazy) {"""
if marker not in text:
    if args.check:
        raise SystemExit("Shared-session patch missing")
    if text.count(anchor) != 1:
        raise SystemExit("Unexpected upstream shared-session anchor")
    path.write_text(text.replace(anchor, insert), encoding="utf8", newline="\n")
elif insert not in text:
    raise SystemExit("Shared-session patch marker exists but implementation differs")
print("Shared normal/stable session patch: present")
